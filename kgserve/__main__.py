"""Command line interface: ``python -m kgserve <command>``."""

from __future__ import annotations

import argparse
import logging
import re
import sys
import tempfile
import urllib.parse
from pathlib import Path

from . import __version__, rdffiles
from .zenodo import Zenodo

VOID_URI_SPACE = "http://rdfs.org/ns/void#uriSpace"


def cmd_sync(args: argparse.Namespace) -> None:
    from .config import SyncConfig
    from .sync import Syncer

    Syncer(SyncConfig.from_env()).run(once=args.once, force=args.force)


def cmd_ld(args: argparse.Namespace) -> None:
    from .config import LDConfig
    from .ld.server import serve

    serve(LDConfig.from_env())


def cmd_resolve(args: argparse.Namespace) -> None:
    record = Zenodo(args.api).record(args.record, not args.no_follow)
    print(f"{record.title}\n  version {record.version or '-'} ({record.publication_date}), {record.doi}"
          f"\n  concept {record.conceptdoi}, license {record.license or '-'}\n  {record.html_url}")
    loadable = set(rdffiles.select([f.key for f in record.files], [], []))
    for f in record.files:
        print(f"  {'*' if f.key in loadable else ' '} {f.key:40} {f.size / 1e6:10.1f} MB")
    print("  (* = loaded by default)")


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:40] or "kg"


def find_uri_spaces(zenodo: Zenodo, record, max_size: int = 50_000_000) -> list[str]:
    """Look for ``void:uriSpace`` in the record's small RDF files (e.g. a VoID description)."""
    import rdflib

    found: list[str] = []
    for f in sorted(record.files, key=lambda f: ("void" not in f.key.lower(), f.size)):
        fmt = rdffiles.detect(f.key)
        if fmt is None or f.size > max_size:
            continue
        with tempfile.TemporaryDirectory() as tmp:
            item = rdffiles.load_items(f.key, zenodo.download(f, Path(tmp) / f.key), lambda _: None)[0]
            graph = rdflib.Dataset()
            with item.open() as stream:
                graph.parse(stream, format={"nt": "nt", "nq": "nquads", "ttl": "turtle", "trig": "trig",
                                            "rdf": "xml", "jsonld": "json-ld", "n3": "n3"}[fmt.ext])
            found += [str(o) for o in graph.objects(None, rdflib.URIRef(VOID_URI_SPACE)) if str(o) not in found]
        if found:
            break
    return found


def cmd_init(args: argparse.Namespace) -> None:
    zenodo = Zenodo(args.api)
    record = zenodo.record(args.record)
    uri_spaces = [] if args.no_void else find_uri_spaces(zenodo, record)
    base_iri = uri_spaces[0] if uri_spaces else ""
    # A w3id.org/purl.org style IRI usually starts with the KG's short name.
    path = urllib.parse.urlsplit(base_iri).path.strip("/").split("/") if base_iri else []
    name = args.name or (path[0] if path and path[0] else _slug(record.title))
    lines = [
        f"# Generated by `kgserve init` for {record.title}",
        f"ZENODO_RECORD={record.conceptdoi or record.doi}",
        f"KG_TITLE={record.title}",
        f"PUBLIC_URL={args.public_url.rstrip('/')}",
        f"BASE_PATH=/{name}",
        f"RESOURCE_PATH=/{name}/id",
        f"KG_BASE_IRI={base_iri}" if base_iri else "# KG_BASE_IRI=  (not found in the record's VoID: set it to the IRI namespace to dereference)",
        "HTTP_PORT=8080",
        "SYNC_INTERVAL=3600",
    ]
    if len(uri_spaces) > 1:
        lines.append(f"# Other void:uriSpace values found: {' '.join(uri_spaces[1:])}")
    text = "\n".join(lines) + "\n"
    if args.output == "-":
        sys.stdout.write(text)
    else:
        Path(args.output).write_text(text)
        print(f"Wrote {args.output}", file=sys.stderr)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="kgserve", description=__doc__)
    parser.add_argument("--version", action="version", version=__version__)
    parser.add_argument("-v", "--verbose", action="store_true")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("sync", help="keep the triple store in sync with the Zenodo record (daemon)")
    p.add_argument("--once", action="store_true", help="sync once and exit")
    p.add_argument("--force", action="store_true", help="reload even if the store is up to date")
    p.set_defaults(func=cmd_sync)

    p = sub.add_parser("ld", help="run the linked-data server")
    p.set_defaults(func=cmd_ld)

    for name, func, helptext in (("resolve", cmd_resolve, "show the latest version of a record and its files"),
                                 ("init", cmd_init, "write a .env configuration for a Zenodo record")):
        p = sub.add_parser(name, help=helptext)
        p.add_argument("record", help="Zenodo record id, DOI or URL")
        p.add_argument("--api", default="https://zenodo.org/api")
        p.set_defaults(func=func)
    sub.choices["resolve"].add_argument("--no-follow", action="store_true", help="do not follow to the latest version")
    init = sub.choices["init"]
    init.add_argument("-o", "--output", default=".env", help="output file ('-' for stdout)")
    init.add_argument("--public-url", default="http://localhost:8080", help="public origin of the service")
    init.add_argument("--name", help="short name used in URL paths (default: from the IRI namespace or title)")
    init.add_argument("--no-void", action="store_true", help="do not download small files to look for void:uriSpace")

    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO,
                        format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    args.func(args)


if __name__ == "__main__":
    main()
